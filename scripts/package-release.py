#!/usr/bin/env python3
"""Prepare segmented USB assets and application-only OTA; never flash or publish."""
from pathlib import Path
import hashlib,json,re,shlex,sys
ROOT=Path(__file__).resolve().parents[1]
def digest(data):return hashlib.sha256(data).hexdigest()
def package(version,source,board):
 if not re.fullmatch(r'\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?',version):raise ValueError('Invalid version')
 spec=json.loads((ROOT/'hardware/boards.json').read_text())[board]
 if f'"{version}"' not in (ROOT/'firmware/LooiWifiOta/LooiWifiOta.h').read_text():raise ValueError('Version mismatch')
 snapshot=json.loads((source/'build-source-info.json').read_text())
 current={str(p.relative_to(ROOT)):digest(p.read_bytes()) for p in (ROOT/'firmware/LooiWifiOta').glob('*') if p.suffix in ['.ino','.h']}
 if snapshot['source_sha256']!=current:raise ValueError('Source changed during build; rebuild before packaging')
 dest=ROOT/'dist';dest.mkdir(exist_ok=True)
 prefix='looi-s3' if board=='n16r8' else 'looi-s3-n8r8'
 base=f'https://github.com/xlle-er/LOOI-DF26-Firmware/releases/download/v{version}/'
 app=(source/'LooiWifiOta.ino.bin').read_bytes()
 marker=f"LOOI_HW_V1|{board}|1|{spec['partition']}|END".encode()
 if not 32<=len(app)<=0x300000 or app[0]!=0xe9 or marker not in app:raise ValueError('Invalid/incompatible application binary')
 # flash_args is generated by the pinned Arduino core, not a hand-maintained address list.
 lines=(source/'flash_args').read_text().splitlines();parts=[]
 for line in lines:
  tokens=shlex.split(line)
  if len(tokens)!=2 or not tokens[0].startswith('0x'):continue
  offset=int(tokens[0],16);path=Path(tokens[1]);path=path if path.is_absolute() else source/path
  data=path.read_bytes()
  if not data:raise ValueError('Empty USB segment')
  filename=f'{prefix}-{path.name}'
  (dest/filename).write_bytes(data)
  parts.append({'offset':offset,'size':len(data),'sha256':digest(data),'path':filename,'url':base+filename})
 if {p['offset'] for p in parts}!={0,0x8000,0xe000,0x10000}:raise ValueError('Unexpected flash layout')
 for a,b in zip(sorted(parts,key=lambda p:p['offset']),sorted(parts,key=lambda p:p['offset'])[1:]):
  if a['offset']+a['size']>b['offset']:raise ValueError('Overlapping flash segments')
 if next(p for p in parts if p['offset']==0x10000)['sha256']!=digest(app):raise ValueError('Application mismatch')
 appname=prefix+'.bin';(dest/appname).write_bytes(app)
 manifest={'version':version,'chip':'ESP32-S3',**{k:spec[k] for k in ['board','flash_mb','psram','psram_mb','partition','hardware_protocol']},'size':len(app),'sha256':digest(app),'url':base+appname}
 (dest/(prefix+'-manifest.json')).write_text(json.dumps(manifest,indent=2)+'\n')
 usb={**manifest,'name':'LOOI '+board.upper(),'builds':[{'chipFamily':'ESP32-S3','parts':parts}], 'partition_sha256':next(p['sha256'] for p in parts if p['offset']==0x8000)}
 (dest/(prefix+'-usb.json')).write_text(json.dumps(usb,indent=2)+'\n')
 sums={p['path']:p['sha256'] for p in parts};sums[appname]=digest(app)
 (dest/(prefix+'-SHA256SUMS')).write_text(''.join(f'{sha}  {name}\n' for name,sha in sorted(sums.items())))
 # Legacy default profile asset names remain valid.
 if board=='n16r8':(dest/'SHA256SUMS').write_text((dest/(prefix+'-SHA256SUMS')).read_text())
 info={'version':version,'board':board,'esp32_arduino':'3.3.12','binary_sha256':digest(app),'flashed':False,'fqbn':snapshot['fqbn'],'source_sha256':snapshot['source_sha256']}
 (dest/(prefix+'-build-info.json')).write_text(json.dumps(info,indent=2)+'\n')
 print(f'Prepared {board} v{version}; no release published or hardware flashed')
if __name__=='__main__':package(sys.argv[1],Path(sys.argv[2]).resolve(),sys.argv[3] if len(sys.argv)>3 else 'n16r8')

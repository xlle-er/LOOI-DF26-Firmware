#!/usr/bin/env python3
"""Generate consumers from hardware/boards.json; --check never edits files."""
from pathlib import Path
import argparse,json
ROOT=Path(__file__).resolve().parents[1]
def outputs():
 source=ROOT/'hardware/boards.json';boards=json.loads(source.read_text());specs=list(boards.values())
 allowed=specs[0]['allowed_gpio'];default=list(specs[0]['default_pins'].values())
 if any(s['allowed_gpio']!=allowed or list(s['default_pins'].values())!=default for s in specs):raise ValueError('This generator expects identical motor GPIO policy for supported profiles')
 header='#pragma once\n// Generated by scripts/sync-hardware.py from hardware/boards.json.\nconstexpr int HARDWARE_ALLOWED_PINS[] = {'+','.join(map(str,allowed))+'};\nconstexpr bool allowedMotorPin(int pin) {\n  for(int allowed : HARDWARE_ALLOWED_PINS) if(pin==allowed) return true;\n  return false;\n}\n#define LOOI_DEFAULT_PINS '+','.join(map(str,default))+'\n'
 data={ROOT/'firmware/LooiWifiOta/HardwarePins.h':header,ROOT/'installer/boards.json':source.read_text()}
 sibling=ROOT.parent/'LOOI-DF26-Skill/looi_deploy'
 if sibling.exists():data[sibling/'boards.json']=source.read_text()
 return data
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
 for path,text in outputs().items():
  if args.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit('Outdated hardware consumer: '+str(path))
  else:path.write_text(text)
